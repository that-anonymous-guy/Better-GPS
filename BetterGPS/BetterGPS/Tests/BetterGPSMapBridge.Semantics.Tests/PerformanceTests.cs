using BetterGPSNavigation;
internal static class PerformanceTests
{
    public static void Run()
    {
        var basePath=Path.GetFullPath("validation/performance/self-tests");
        var root=Path.Combine(basePath,Guid.NewGuid().ToString("N"));Directory.CreateDirectory(root);
        int assertions=0;void Check(bool value,string message){assertions++;if(!value)throw new Exception(message);}
        Check(LiveProtocol.AllowedInstructions.Contains("SHARP_LEFT")&&LiveProtocol.AllowedInstructions.Contains("SHARP_RIGHT"),"Sharp turns generated by the planner are legal live actions");
        Check(RoadIdentityResolver.HardBoundary("SHARP_RIGHT")&&RoadIdentityResolver.HardBoundary("SHARP_LEFT"),"Captured continuity stops at sharp turns");
        try
        {
            File.WriteAllText(Path.Combine(root,"root.sii"),"SiiNunit { @include \"nested.sui\" }");
            File.WriteAllText(Path.Combine(root,"nested.sui"),"road_look : road.test { lanes_right[]: lane.test }");
            File.WriteAllText(Path.Combine(root,"other.sii"),"SiiNunit { model : model.test {} }");
            File.WriteAllText(Path.Combine(root,"binary.sii"),"BSII\0test");
            var fs=new MountedDirectoryFileSystem(root);var index=new SiiClassIndex(fs,"road_look");
            Check(index.MayContain("/root.sii"),"Road classes in headerless included fragments are retained");
            Check(!index.MayContain("/other.sii"),"Unrelated model definitions are skipped");
            Check(index.MayContain("/binary.sii"),"Binary encodings retain the full parser");
            Check(index.MayContain("/missing.sii"),"Missing inputs preserve parser error reporting");
            var mount=Path.Combine(root,"mount.scs");File.WriteAllText(mount,"first");
            var cache=Path.Combine(root,"cache");int builds=0;
            AssetIndexCache.Configure(fs,cache,[new(mount,"mod")]);
            int Read()=>AssetIndexCache.Get(fs,"test",()=>++builds);
            Check(Read()==1&&Read()==1&&builds==1,"Validated indexes are reused");
            var path=Directory.GetFiles(cache).Single();File.WriteAllText(path,"corrupt");
            Check(Read()==2,"Corrupt caches are rebuilt");
            File.WriteAllText(mount,"updated mount with changed length");
            var changed=new MountedDirectoryFileSystem(root);AssetIndexCache.Configure(changed,cache,[new(mount,"mod")]);
            Check(AssetIndexCache.Get(changed,"test",()=>++builds)==3,"Changed mods invalidate indexes");
            File.WriteAllText(Path.Combine(root,"root.sii"),"changed");
            Check(fs.ReadAllText("/root.sii")=="changed","Directory mounts keep fresh file reads");
        }
        finally{if(!Path.GetFullPath(root).StartsWith(basePath+Path.DirectorySeparatorChar))throw new Exception("Test cleanup scope");Directory.Delete(root,true);}
        Console.WriteLine($"PASS: {assertions} performance cache and include assertions.");
    }
}
