"""Generate stock integrated-GPS model bounds, never screen-space hitboxes.

All measured stock GPS vertices must pass; all sibling cluster vertices must
fail. Runtime uses only the resulting constexpr table, with no asset parsing.
"""
from pathlib import Path
import argparse, hashlib, json, math, struct

SUPPORTED = ('kenworth.t680', 'kenworth.t680_2022', 'kenworth.w900',
             'mack.anthem', 'mack.pinnacle', 'peterbilt.389', 'peterbilt.579',
             'volvo.vnl', 'volvo.vnl2018', 'volvo.vnl2025', 'volvo.vnr_e',
             'freightliner.cascadia2019', 'freightliner.cascadia2024', 'westernstar.49x', 'westernstar.57x', 'westernstar.5700xe', 'intnational.lonestar', 'intnational.lt')

def dot(a, b): return sum(x*y for x,y in zip(a,b))
def unit(v): return [x/math.sqrt(dot(v,v)) for x in v]
def cross(a,b): return [a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]]

def vertices(root, row):
    data=(root/Path(row['model']).with_suffix('.pmg').as_posix().lstrip('/')).read_bytes()
    u=lambda at:struct.unpack_from('<I',data,at)[0]
    at=u(84)+100*row['piece'];stride,pos,_,uv=struct.unpack_from('<4I',data,at+60)
    indices=struct.unpack_from('<'+'H'*u(at),data,u(at+96));used=set()
    for i in range(0,len(indices)-2,3):
        tri=indices[i:i+3]
        tile=tuple(math.floor(sum(struct.unpack_from('<2f',data,uv+j*stride)[k] for j in tri)/3+1e-7) for k in range(2))
        if tile==tuple(row['tile']):used.update(tri)
    return [struct.unpack_from('<3f',data,pos+i*stride) for i in sorted(used)]

def build(stock, audit):
    rows=json.loads(audit.read_text());rows=[r for r in rows if r['truck'] in SUPPORTED]
    unique={}
    for row in rows:
        key=(row['truck'],row['model'],row['piece'],tuple(row['tile']),row['role'])
        unique.setdefault(key,row)
    rows=list(unique.values());bounds=[];report=[]
    for truck,icuc in ([(t,t in ('westernstar.49x','westernstar.5700xe')) for t in SUPPORTED]+[(t,True) for t in SUPPORTED if t.startswith('freightliner.cascadia')]):
        gps=[r for r in rows if r['truck']==truck and r['role']=='infotainment/GPS'
             and (not truck.startswith('freightliner.cascadia') or (r['evidence']['ui']=='/ui/gps.sii' if icuc else r['evidence']['ui'] in ('/ui/dashboard/freightliner_cascadia_icc5_gps.sii','/ui/dashboard/freightliner_cascadia_2024_gps.sii')))]
        assert gps, truck
        source=gps[0];center=source['center'];u=unit(source['uDirection'])
        v=unit([b-dot(source['vDirection'],u)*a for a,b in zip(u,source['vDirection'])]);n=unit(cross(u,v));axes=[u,v,n]
        points=[p for r in gps for p in vertices(stock/'extracted',r)]
        project=lambda p:[dot([a-b for a,b in zip(p,center)],axis) for axis in axes]
        low=[min(project(p)[k] for p in points)-.002 for k in range(3)]
        high=[max(project(p)[k] for p in points)+.002 for k in range(3)]
        inside=lambda p:all(low[k]-1e-8<=project(p)[k]<=high[k]+1e-8 for k in range(3))
        assert all(inside(p) for p in points),truck
        clusters=[r for r in rows if r['truck']==truck and r['role']=='cluster']
        cluster_points=[p for r in clusters for p in vertices(stock/'extracted',r)]
        assert not any(inside(p) for p in cluster_points),f'{truck}: cluster overlaps GPS bounds'
        bounds.append((truck,icuc,center,u,v,n,low,high))
        report.append(dict(truck=truck,icuc=icuc,gps_models=len(gps),gps_vertices=len(points),
                           rejected_cluster_vertices=len(cluster_points),margin_mm=2))
    def vector(v):return '{'+','.join(f'{x:.10f}' for x in v)+'}'
    text='''#pragma once
// Generated by scripts/build_touch_gps_bounds.py from stock PMG GPS surfaces.
// Units: metres in native model space. The 2 mm margin is not a cursor tolerance.
namespace bettergps_overlay {
struct TouchGpsBounds {
 const char* vehicle;bool icuc;std::array<double,3> center,u,v,n,low,high;
 bool contains(const touch_geometry::Register& p)const{
  if((p.valid&7)!=7)return false;
  const std::array<double,3>* axes[]={&u,&v,&n};
  for(unsigned k=0;k<3;++k){double x=0;for(unsigned j=0;j<3;++j){if(!std::isfinite(p.value[j]))return false;x+=(double(p.value[j])-center[j])*(*axes[k])[j];}if(x<low[k]||x>high[k])return false;}return true;
 }
};
inline constexpr TouchGpsBounds touchGpsBounds[]={
'''
    for truck,icuc,*vectors in bounds:text+=' {"'+truck+'",'+str(icuc).lower()+','+','.join(vector(v) for v in vectors)+'},\n'
    text+='''};
inline const TouchGpsBounds* touch_gps_bounds(const ManagedDevice& d){
 // A truck name alone must never classify a phone, accessory or cluster producer.
 if(!(managed_is_international(d)||managed_is_zonar(d)||managed_is_icc5(d)||managed_is_navplus(d)||managed_is_copilot(d)||managed_is_mack(d)||managed_is_volvo18(d)||managed_is_volvo25(d)||managed_is_vnl2014(d)))return nullptr;
 for(const auto& bounds:touchGpsBounds)if(d.vehicle==bounds.vehicle&&bounds.icuc==managed_is_zonar(d))return &bounds;return nullptr;
}
}
'''
    return text,report

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--stock-root',type=Path,required=True);p.add_argument('--audit',type=Path,required=True);p.add_argument('--check',action='store_true');p.add_argument('--report',type=Path)
    args=p.parse_args();text,report=build(args.stock_root,args.audit)
    output=Path(__file__).resolve().parents[1]/'generated/TouchGpsBounds.h'
    if args.check:assert output.read_text()==text,'Generated GPS model bounds are stale'
    else:output.write_text(text,encoding='utf-8',newline='\n')
    if args.report:args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2)+'\n')
    print('PASS:',len(report),'stock truck identities;',sum(r['gps_vertices'] for r in report),'GPS vertices accepted;',sum(r['rejected_cluster_vertices'] for r in report),'cluster vertices rejected')
