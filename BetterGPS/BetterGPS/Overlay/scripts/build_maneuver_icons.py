"""Bake the supplied Google silhouettes; rendering tints these alpha masks white.
Run from any directory with Python + Pillow. No runtime image loading is needed.
"""
from pathlib import Path
from PIL import Image
import hashlib

root = Path(__file__).resolve().parents[1]
names = ['straight', 'turn_left', 'turn_right', 'turn_sharp_left', 'turn_sharp_right',
         'turn_slight_left', 'turn_slight_right', 'fork_left', 'fork_right',
         'merge', 'merge_left', 'merge_right', 'turn_u_turn_clockwise',
         'turn_u_turn_counterclockwise', 'roundabout_counterclockwise',
         'roundabout_exit_counterclockwise', 'destination', 'exit_left', 'exit_right']
lines = ['// Generated by scripts/build_maneuver_icons.py from the supplied Google PNGs.',
         '#pragma once', '#include <cstdint>', '#include <string>',
         'namespace bettergps_overlay {',
         'struct ManeuverIcon { const uint8_t* alpha; int size; };']
for name in names:
    path = root / 'BetterGPS_assets/material/ui/maneuvers' / f'ic_{name}.png'
    if name.startswith('exit_'):
        path = root / 'generated' / ('ramp_' + name[5:] + '.png')
    source = Image.open(path).convert('RGBA')
    # The official images already have transparent backgrounds. Use alpha only:
    # this preserves antialiasing and removes the black foreground color.
    mask = source.getchannel('A').resize((96, 96), Image.Resampling.LANCZOS)
    lines += [f'// {path.name}: SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}',
              f'inline constexpr uint8_t icon_{name}[] = {{']
    data = mask.tobytes()
    lines.extend(','.join(map(str, data[i:i+96]))+',' for i in range(0,len(data),96))
    lines += ['};']
lines += ['inline ManeuverIcon maneuver_icon(const std::string& action) {',
          '#define ICON(name) return {icon_##name, 96}',
          'if(action=="TURN_LEFT"||action=="left") { ICON(turn_left); }',
          'if(action=="TURN_RIGHT"||action=="right") { ICON(turn_right); }',
          'if(action=="SHARP_LEFT") { ICON(turn_sharp_left); }',
          'if(action=="SHARP_RIGHT") { ICON(turn_sharp_right); }',
          'if(action=="SLIGHT_LEFT") { ICON(turn_slight_left); }',
          'if(action=="SLIGHT_RIGHT") { ICON(turn_slight_right); }',
          'if(action=="EXIT_LEFT") { ICON(exit_left); }',
          'if(action=="EXIT_RIGHT") { ICON(exit_right); }',
          'if(action=="KEEP_LEFT") { ICON(fork_left); }',
          'if(action=="KEEP_RIGHT") { ICON(fork_right); }',
          'if(action=="MERGE_LEFT") { ICON(merge_left); }',
          'if(action=="MERGE_RIGHT") { ICON(merge_right); }',
          'if(action=="MERGE"||action=="merge") { ICON(merge); }',
          'if(action=="U_TURN_RIGHT") { ICON(turn_u_turn_clockwise); }',
          'if(action=="U_TURN"||action=="U_TURN_LEFT"||action=="turn around") { ICON(turn_u_turn_counterclockwise); }',
          'if(action=="ROUNDABOUT_EXIT") { ICON(roundabout_exit_counterclockwise); }',
          'if(action=="ROUNDABOUT"||action=="roundabout") { ICON(roundabout_counterclockwise); }',
          'if(action=="ARRIVED"||action=="COMPLETE") { ICON(destination); }',
          'if(action=="CONTINUE"||action=="STAY"||action=="CONTINUE_AT_FORK"||action=="FORK_STRAIGHT"||action=="USE_SELECTED_LANES"||action=="stay"||action=="use selected lanes"||action=="go straight"||action=="straight") { ICON(straight); }',
          'return {nullptr,0};', '#undef ICON', '}', '}']
(root/'GoogleManeuverIcons.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
